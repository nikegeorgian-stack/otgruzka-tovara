function esc(s) {
  return s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")
}

const lines = []
const seen = new Set()

function add(key, value) {
  // Всегда пересобираем блок extras целиком (иначе remove+has стирает старые ключи).
  if (seen.has(key)) return
  seen.add(key)
  lines.push(`  '${key}': '${esc(value)}',`)
}

function tabGuide(view, slug, title, blurb, s1Title, s1Body, s2) {
  add(`coach.guide.${view}.${slug}.title`, title)
  add(`coach.guide.${view}.${slug}.blurb`, blurb)
  add(`coach.guide.${view}.${slug}.s1.title`, s1Title)
  add(`coach.guide.${view}.${slug}.s1.body`, s1Body)
  if (s2) {
    add(`coach.guide.${view}.${slug}.s2.title`, s2[0])
    add(`coach.guide.${view}.${slug}.s2.body`, s2[1])
  }
}

function actionGuide(view, slug, title, blurb, s1Title, s1Body) {
  tabGuide(view, slug, title, blurb, s1Title, s1Body)
}

